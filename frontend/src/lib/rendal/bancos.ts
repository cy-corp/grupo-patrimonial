const POR_CODIGO = new Map(BANCOS.map((banco) => [banco.code, banco]));

export function bancoByCode(code: string) {
  return POR_CODIGO.get(code);
}

export function labelBanco(code: string) {
  const banco = POR_CODIGO.get(code);
  return banco ? `${banco.code} · ${banco.name}` : "";
}

function fold(value: string) {
  return value.normalize("NFD").replace(/\p{M}/gu, "").toLowerCase();
}

/** Lista curta para o combobox: destaque sem busca, ou até 30 resultados por nome ou código. */
export function buscarBancos(query: string): Banco[] {
  const trimmed = query.trim();
  if (!trimmed) {
    return BANCOS_DESTAQUE.flatMap((code) => {
      const banco = POR_CODIGO.get(code);
      return banco ? [banco] : [];
    });
  }

  const folded = fold(trimmed);
  const digits = trimmed.replace(/\D/g, "");
  const byName = /\p{L}/u.test(trimmed);
  const ranked = BANCOS.flatMap((banco) => {
    let score = 0;
    if (digits) {
      const padded = digits.padStart(3, "0");
      if (banco.code === padded) score = 100;
      else if (banco.code.startsWith(digits)) score = 80;
    }
    if (byName) {
      const name = fold(banco.name);
      if (name.startsWith(folded)) score = Math.max(score, 70);
      else if (name.includes(folded)) score = Math.max(score, 60);
    }
    return score > 0 ? [{ banco, score }] : [];
  });

  ranked.sort(
    (a, b) => b.score - a.score || a.banco.name.localeCompare(b.banco.name, "pt"),
  );
  return ranked.slice(0, 30).map((item) => item.banco);
}

export type ContaBancaria = {
  id: string;
  code: string;
  agencia: string;
  conta: string;
  digito: string;
};

export function formatContaBancaria(conta: ContaBancaria) {
  const banco = labelBanco(conta.code);
  const numero = conta.digito ? `${conta.conta}-${conta.digito}` : conta.conta;
  return [banco, conta.agencia ? `ag ${conta.agencia}` : "", numero ? `conta ${numero}` : ""]
    .filter(Boolean)
    .join(" · ");
}

export function erroConta(conta: ContaBancaria) {
  return {
    code: bancoByCode(conta.code) ? "" : "Escolha o banco na lista.",
    agencia: /^\d{4}$/.test(conta.agencia) ? "" : "A agência tem 4 dígitos.",
    conta: /^\d{4,13}$/.test(conta.conta) ? "" : "Informe a conta, sem o dígito.",
    digito: conta.digito === "" || /^[0-9xX]{1,2}$/.test(conta.digito) ? "" : "Use 1 ou 2 caracteres.",
  };
}

export function sanitizeContas(value: unknown): ContaBancaria[] {
  if (!Array.isArray(value)) return [];
  return value.slice(0, 4).flatMap((item) => {
    if (!item || typeof item !== "object") return [];
    const row = item as Partial<ContaBancaria>;
    const code = typeof row.code === "string" && POR_CODIGO.has(row.code) ? row.code : "";
    const id = typeof row.id === "string" && row.id.length > 0 ? row.id.slice(0, 40) : "";
    if (!id) return [];
    return [
      {
        id,
        code,
        agencia: typeof row.agencia === "string" ? row.agencia.replace(/\D/g, "").slice(0, 4) : "",
        conta: typeof row.conta === "string" ? row.conta.replace(/\D/g, "").slice(0, 13) : "",
        digito: typeof row.digito === "string" ? row.digito.replace(/[^0-9xX]/g, "").slice(0, 2) : "",
      },
    ];
  });
}
